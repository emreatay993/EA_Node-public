def _run_parent(args: argparse.Namespace) -> int:
    renderers = _parse_renderer_names(args.only)
    if args.selftest and not args.only:
        renderers = list(QUICK_RENDERERS)

    output_dir = Path(args.output_dir).resolve() if args.output_dir else DEFAULT_OUTPUT_ROOT / datetime.now().strftime("%Y%m%d_%H%M%S")
    output_dir.mkdir(parents=True, exist_ok=True)

    if args.input:
        input_docx = Path(args.input).resolve()
        if not input_docx.exists():
            raise SystemExit(f"Input DOCX does not exist: {input_docx}")
    else:
        input_docx = output_dir / "sample.docx"
        write_sample_docx(input_docx)

    results = []
    for name in renderers:
        print(f"Rendering {name}...")
        renderer_dir = output_dir / name
        renderer_dir.mkdir(parents=True, exist_ok=True)
        result = _run_subprocess_renderer(
            name,
            input_docx,
            renderer_dir,
            max_pages=args.max_pages,
            timeout_s=args.timeout,
        )
        results.append(result)
        print(f"  {result['status']}: {result['note']}")

    report: dict[str, object] = {
        "schema": 1,
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "input_docx": _rel(input_docx, output_dir),
        "output_dir": str(output_dir),
        "results": results,
    }
    report_path = output_dir / "report.json"
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")
    comparison_path = _write_comparison_html(report, output_dir)

    ok_count = sum(1 for item in results if item["status"] == "ok")
    skipped_count = sum(1 for item in results if item["status"] == "skipped")
    failed_count = sum(1 for item in results if item["status"] == "failed")
    print()
    print(f"Report: {report_path}")
    print(f"Comparison: {comparison_path}")
    print(f"Summary: {ok_count} ok, {skipped_count} skipped, {failed_count} failed")
    if args.selftest and ok_count == 0:
        return 1
    return 0 if failed_count == 0 or args.keep_going_exit_zero else 1


def _list_renderers() -> int:
    for renderer in RENDERERS.values():
        print(f"{renderer.name:<24} {renderer.kind:<18} {renderer.description}")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", help="DOCX file to render. A sample DOCX is generated when omitted.")
    parser.add_argument("--output-dir", help="Directory for reports and rendered artifacts.")
    parser.add_argument("--only", action="append", help="Renderer name or comma-separated renderer names.")
    parser.add_argument("--max-pages", type=int, default=3, help="Maximum PDF pages to rasterize per renderer.")
    parser.add_argument("--timeout", type=int, default=180, help="Seconds allowed per renderer subprocess.")
    parser.add_argument("--selftest", action="store_true", help="Run a quick subset suitable for smoke testing.")
    parser.add_argument("--list", action="store_true", help="List available renderer candidates and exit.")
    parser.add_argument("--keep-going-exit-zero", action="store_true", help="Return 0 even when some renderers fail.")
    parser.add_argument("--worker", choices=sorted(RENDERERS), help=argparse.SUPPRESS)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.list:
        return _list_renderers()
    if args.worker:
        if not args.input or not args.output_dir:
            parser.error("--worker requires --input and --output-dir")
        return _worker_main(args)
    return _run_parent(args)


if __name__ == "__main__":
    raise SystemExit(main())
