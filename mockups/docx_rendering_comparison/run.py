def _render_python_docx_html_qt(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    from docx import Document

    document = Document(str(input_docx.resolve()))
    blocks: list[str] = []
    for paragraph in document.paragraphs:
        text = paragraph.text.strip()
        if not text:
            continue
        style = paragraph.style.name.lower() if paragraph.style else ""
        escaped = html.escape(text)
        if "heading 1" in style or "title" in style:
            blocks.append(f"<h2>{escaped}</h2>")
        elif "heading 2" in style:
            blocks.append(f"<h3>{escaped}</h3>")
        elif "list" in style:
            blocks.append(f"<p class=\"muted\">- {escaped}</p>")
        else:
            blocks.append(f"<p>{escaped}</p>")
    for table in document.tables:
        rows = []
        for row_index, row in enumerate(table.rows):
            cells = "".join(
                f"<{'th' if row_index == 0 else 'td'}>{html.escape(cell.text)}</{'th' if row_index == 0 else 'td'}>"
                for cell in row.cells
            )
            rows.append(f"<tr>{cells}</tr>")
        blocks.append(f"<table>{''.join(rows)}</table>")
    html_text = _html_document("python-docx extracted HTML", "\n".join(blocks))
    html_path = output_dir / "python_docx.html"
    pdf_path = output_dir / "python_docx_qt.pdf"
    artifacts, pages = _write_html_then_pdf(
        html_text=html_text,
        html_path=html_path,
        pdf_path=pdf_path,
        output_dir=output_dir,
        max_pages=max_pages,
    )
    return {"note": "Extracted paragraphs/tables with python-docx, then printed with Qt WebEngine.", "artifacts": artifacts, "pages": pages}


