def _render_libreoffice_pdf(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    executable = _find_libreoffice_executable()
    if not executable:
        raise SkipRenderer("LibreOffice executable was not found on PATH.")
    result = subprocess.run(
        [
            executable,
            "--headless",
            "--convert-to",
            "pdf",
            "--outdir",
            str(output_dir.resolve()),
            str(input_docx.resolve()),
        ],
        text=True,
        capture_output=True,
        timeout=120,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(result.stderr.strip() or result.stdout.strip() or "LibreOffice conversion failed.")
    produced = output_dir / f"{input_docx.stem}.pdf"
    pdf_path = output_dir / "libreoffice.pdf"
    if produced.exists() and produced != pdf_path:
        produced.replace(pdf_path)
    artifacts, pages = _pdf_result(pdf_path, output_dir, max_pages)
    return {"note": "Rendered through LibreOffice headless CLI.", "artifacts": artifacts, "pages": pages}


def _render_pypandoc_html_qt(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    import pypandoc

    raw_html = output_dir / "pandoc_raw.html"
    media_dir = output_dir / "media"
    media_dir.mkdir(exist_ok=True)
    pypandoc.convert_file(
        str(input_docx.resolve()),
        "html",
        outputfile=str(raw_html.resolve()),
        extra_args=["--standalone", f"--extract-media={media_dir.resolve()}"],
    )
    html_text = _inject_css_if_full_html(raw_html.read_text(encoding="utf-8"))
    html_path = output_dir / "pypandoc.html"
    pdf_path = output_dir / "pypandoc_qt.pdf"
    artifacts, pages = _write_html_then_pdf(
        html_text=html_text,
        html_path=html_path,
        pdf_path=pdf_path,
        output_dir=output_dir,
        max_pages=max_pages,
    )
    artifacts["raw_html"] = raw_html
    return {"note": "Converted with Pandoc, then printed with Qt WebEngine.", "artifacts": artifacts, "pages": pages}


def _render_mammoth_html_qt(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    import mammoth

    with input_docx.open("rb") as handle:
        result = mammoth.convert_to_html(handle)
    messages = "; ".join(str(message) for message in result.messages)
    html_text = _html_document("Mammoth HTML conversion", result.value)
    html_path = output_dir / "mammoth.html"
    pdf_path = output_dir / "mammoth_qt.pdf"
    artifacts, pages = _write_html_then_pdf(
        html_text=html_text,
        html_path=html_path,
        pdf_path=pdf_path,
        output_dir=output_dir,
        max_pages=max_pages,
    )
    note = "Converted with Mammoth semantic HTML, then printed with Qt WebEngine."
    if messages:
        note = f"{note} Mammoth messages: {messages}"
    return {"note": note, "artifacts": artifacts, "pages": pages}


def _markdown_to_html(markdown_text: str, title: str) -> str:
    try:
        import marko

        body = marko.convert(markdown_text)
    except Exception:
        body = f"<pre class=\"extracted\">{html.escape(markdown_text)}</pre>"
    return _html_document(title, body)


def _render_docling_html_qt(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    from docling.document_converter import DocumentConverter

    converter = DocumentConverter()
    result = converter.convert(str(input_docx.resolve()))
    document = result.document
    if hasattr(document, "export_to_html"):
        html_text = document.export_to_html()
        html_text = _inject_css_if_full_html(html_text)
    else:
        markdown = document.export_to_markdown()
        (output_dir / "docling.md").write_text(markdown, encoding="utf-8")
        html_text = _markdown_to_html(markdown, "Docling conversion")
    html_path = output_dir / "docling.html"
    pdf_path = output_dir / "docling_qt.pdf"
    artifacts, pages = _write_html_then_pdf(
        html_text=html_text,
        html_path=html_path,
        pdf_path=pdf_path,
        output_dir=output_dir,
        max_pages=max_pages,
    )
    markdown_path = output_dir / "docling.md"
    if markdown_path.exists():
        artifacts["markdown"] = markdown_path
    return {"note": "Converted with Docling, then printed with Qt WebEngine.", "artifacts": artifacts, "pages": pages}


