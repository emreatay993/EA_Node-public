def _run_renderer_worker(name: str, input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    renderer = RENDERERS[name]
    output_dir.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    try:
        payload = renderer.func(input_docx, output_dir, max_pages)
        duration_s = time.perf_counter() - started
        return _json_safe_result(
            name=name,
            label=renderer.label,
            kind=renderer.kind,
            status="ok",
            note=str(payload.get("note", "")),
            duration_s=duration_s,
            output_dir=output_dir,
            artifacts=payload.get("artifacts", {}),
            pages=payload.get("pages", []),
        )
    except SkipRenderer as exc:
        duration_s = time.perf_counter() - started
        return _json_safe_result(
            name=name,
            label=renderer.label,
            kind=renderer.kind,
            status="skipped",
            note=str(exc),
            duration_s=duration_s,
            output_dir=output_dir,
        )
    except Exception as exc:  # noqa: BLE001
        duration_s = time.perf_counter() - started
        return _json_safe_result(
            name=name,
            label=renderer.label,
            kind=renderer.kind,
            status="failed",
            note=str(exc),
            duration_s=duration_s,
            output_dir=output_dir,
            details=traceback.format_exc(),
        )


def _parse_renderer_names(values: Iterable[str] | None) -> list[str]:
    if not values:
        return list(RENDERERS)
    requested: list[str] = []
    for value in values:
        requested.extend(part.strip() for part in value.split(",") if part.strip())
    unknown = [name for name in requested if name not in RENDERERS]
    if unknown:
        raise SystemExit(f"Unknown renderer(s): {', '.join(unknown)}")
    return requested


def _worker_main(args: argparse.Namespace) -> int:
    output_dir = Path(args.output_dir).resolve()
    result = _run_renderer_worker(args.worker, Path(args.input).resolve(), output_dir, args.max_pages)
    (output_dir / "result.json").write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps({"name": args.worker, "status": result["status"], "note": result["note"]}))
    return 0


def _run_subprocess_renderer(
    name: str,
    input_docx: Path,
    renderer_dir: Path,
    *,
    max_pages: int,
    timeout_s: int,
) -> dict[str, object]:
    command = [
        sys.executable,
        str(Path(__file__).resolve()),
        "--worker",
        name,
        "--input",
        str(input_docx.resolve()),
        "--output-dir",
        str(renderer_dir.resolve()),
        "--max-pages",
        str(max_pages),
    ]
    try:
        completed = subprocess.run(
            command,
            cwd=ROOT,
            text=True,
            capture_output=True,
            timeout=timeout_s,
            check=False,
        )
    except subprocess.TimeoutExpired as exc:
        renderer = RENDERERS[name]
        return _json_safe_result(
            name=name,
            label=renderer.label,
            kind=renderer.kind,
            status="failed",
            note=f"Timed out after {timeout_s} seconds.",
            duration_s=timeout_s,
            output_dir=renderer_dir,
            details=(exc.stdout or "") + "\n" + (exc.stderr or ""),
        )

    result_path = renderer_dir / "result.json"
    if result_path.exists():
        result = json.loads(result_path.read_text(encoding="utf-8"))
        _prefix_worker_paths(result, renderer_dir)
        result["stdout"] = completed.stdout[-4000:]
        result["stderr"] = completed.stderr[-4000:]
        return result

    renderer = RENDERERS[name]
    return _json_safe_result(
        name=name,
        label=renderer.label,
        kind=renderer.kind,
        status="failed",
        note=f"Worker exited with code {completed.returncode} before writing result.json.",
        duration_s=0.0,
        output_dir=renderer_dir,
        details=completed.stdout[-4000:] + "\n" + completed.stderr[-4000:],
    )


def _prefix_worker_paths(result: dict[str, object], renderer_dir: Path) -> None:
    prefix = renderer_dir.name

    def prefixed(value: str) -> str:
        if not value:
            return value
        normalized = value.replace("\\", "/")
        if Path(normalized).is_absolute() or normalized.startswith("../"):
            return normalized
        if normalized.startswith(f"{prefix}/"):
            return normalized
        return f"{prefix}/{normalized}"

    artifacts = result.get("artifacts", {})
    if isinstance(artifacts, dict):
        result["artifacts"] = {
            key: prefixed(str(path))
            for key, path in artifacts.items()
        }
    pages = result.get("pages", [])
    if isinstance(pages, list):
        result["pages"] = [prefixed(str(path)) for path in pages]


