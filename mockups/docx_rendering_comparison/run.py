class SkipRenderer(RuntimeError):
    """Raised when a renderer is intentionally unavailable on this machine."""


@dataclass(frozen=True)
class Renderer:
    name: str
    label: str
    kind: str
    description: str
    func: Callable[[Path, Path, int], dict[str, object]]


def _rel(path: Path, base: Path) -> str:
    try:
        return path.resolve().relative_to(base.resolve()).as_posix()
    except ValueError:
        return path.resolve().as_posix()


def _json_safe_result(
    *,
    name: str,
    label: str,
    kind: str,
    status: str,
    note: str,
    duration_s: float,
    output_dir: Path,
    artifacts: dict[str, Path] | None = None,
    pages: list[Path] | None = None,
    details: str = "",
) -> dict[str, object]:
    artifacts = artifacts or {}
    pages = pages or []
    return {
        "name": name,
        "label": label,
        "kind": kind,
        "status": status,
        "note": note,
        "duration_s": round(duration_s, 3),
        "artifacts": {key: _rel(value, output_dir) for key, value in artifacts.items()},
        "pages": [_rel(page, output_dir) for page in pages],
        "details": details,
    }


def _check_file(path: Path, label: str) -> None:
    if not path.exists() or path.stat().st_size <= 0:
        raise RuntimeError(f"{label} was not created: {path}")


def _rasterize_pdf(pdf_path: Path, output_dir: Path, *, max_pages: int) -> list[Path]:
    import fitz

    pages_dir = output_dir / "pages"
    pages_dir.mkdir(parents=True, exist_ok=True)
    rendered: list[Path] = []
    with fitz.open(str(pdf_path)) as document:
        page_count = min(len(document), max_pages)
        for index in range(page_count):
            page = document.load_page(index)
            pixmap = page.get_pixmap(matrix=fitz.Matrix(2.0, 2.0), alpha=False)
            page_path = pages_dir / f"page_{index + 1:03d}.png"
            pixmap.save(str(page_path))
            rendered.append(page_path)
    if not rendered:
        raise RuntimeError(f"No pages were rasterized from {pdf_path}")
    return rendered


def _html_document(title: str, body: str) -> str:
    return textwrap.dedent(
        f"""\
        <!doctype html>
        <html>
        <head>
          <meta charset="utf-8">
          <title>{html.escape(title)}</title>
          <style>{HTML_CSS}</style>
        </head>
        <body>
          <h1>{html.escape(title)}</h1>
          <p class="doc-meta">Generated by the DOCX rendering comparison prototype.</p>
          {body}
        </body>
        </html>
        """
    )


def _inject_css_if_full_html(source: str) -> str:
    style = f"<style>{HTML_CSS}</style>"
    lower = source.lower()
    if "</head>" in lower:
        index = lower.rfind("</head>")
        return source[:index] + style + source[index:]
    if "<html" in lower:
        return source
    return _html_document("Pandoc HTML conversion", source)


def _write_html_then_pdf(
    *,
    html_text: str,
    html_path: Path,
    pdf_path: Path,
    output_dir: Path,
    max_pages: int,
) -> tuple[dict[str, Path], list[Path]]:
    html_path.write_text(html_text, encoding="utf-8")
    _html_file_to_pdf_qt(html_path, pdf_path)
    _check_file(pdf_path, "PDF")
    pages = _rasterize_pdf(pdf_path, output_dir, max_pages=max_pages)
    return {"html": html_path, "pdf": pdf_path}, pages


def _html_file_to_pdf_qt(html_path: Path, pdf_path: Path) -> None:
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    os.environ.setdefault("QTWEBENGINE_CHROMIUM_FLAGS", "--disable-gpu --no-sandbox")

    from PyQt6.QtCore import QEventLoop, QTimer, QUrl
    from PyQt6.QtWebEngineCore import QWebEnginePage
    from PyQt6.QtWidgets import QApplication

    app = QApplication.instance() or QApplication(sys.argv[:1])
    page = QWebEnginePage()

    load_state = {"done": False, "ok": False}
    load_loop = QEventLoop()

    def on_load_finished(ok: bool) -> None:
        load_state["done"] = True
        load_state["ok"] = ok
        load_loop.quit()

    page.loadFinished.connect(on_load_finished)
    page.load(QUrl.fromLocalFile(str(html_path.resolve())))
    QTimer.singleShot(30000, load_loop.quit)
    load_loop.exec()
    if not load_state["done"]:
        raise TimeoutError(f"Timed out loading HTML in Qt WebEngine: {html_path}")
    if not load_state["ok"]:
        raise RuntimeError(f"Qt WebEngine failed to load HTML: {html_path}")

    print_state = {"done": False, "ok": False}
    print_loop = QEventLoop()

    def on_pdf_finished(_path: str, ok: bool) -> None:
        print_state["done"] = True
        print_state["ok"] = ok
        print_loop.quit()

    page.pdfPrintingFinished.connect(on_pdf_finished)
    page.printToPdf(str(pdf_path.resolve()))
    QTimer.singleShot(30000, print_loop.quit)
    print_loop.exec()
    page.deleteLater()
    app.processEvents()
    if not print_state["done"]:
        raise TimeoutError(f"Timed out printing HTML to PDF: {html_path}")
    if not print_state["ok"]:
        raise RuntimeError(f"Qt WebEngine failed to print PDF: {pdf_path}")


def _pdf_result(pdf_path: Path, output_dir: Path, max_pages: int) -> tuple[dict[str, Path], list[Path]]:
    _check_file(pdf_path, "PDF")
    pages = _rasterize_pdf(pdf_path, output_dir, max_pages=max_pages)
    return {"pdf": pdf_path}, pages


def _find_libreoffice_executable() -> str | None:
    configured = os.environ.get("LIBREOFFICE_SOFFICE_PATH")
    candidates = [
        Path(configured) if configured else None,
        Path(os.environ.get("LOCALAPPDATA", "")) / "LibreOfficeAdminImage" / "program" / "soffice.exe",
        Path(os.environ.get("ProgramFiles", "")) / "LibreOffice" / "program" / "soffice.exe",
        Path(os.environ.get("ProgramFiles(x86)", "")) / "LibreOffice" / "program" / "soffice.exe",
    ]
    for candidate in candidates:
        if candidate and candidate.exists():
            return str(candidate)
    return shutil.which("soffice") or shutil.which("libreoffice")


def _render_word_com_pdf(input_docx: Path, output_dir: Path, max_pages: int) -> dict[str, object]:
    import win32com.client

    pdf_path = output_dir / "word_com.pdf"
    word = None
    document = None
    try:
        word = win32com.client.DispatchEx("Word.Application")
        word.Visible = False
        word.DisplayAlerts = 0
        document = word.Documents.Open(str(input_docx.resolve()), ReadOnly=True)
        document.ExportAsFixedFormat(str(pdf_path.resolve()), 17)
    finally:
        if document is not None:
            document.Close(False)
        if word is not None:
            word.Quit()
    artifacts, pages = _pdf_result(pdf_path, output_dir, max_pages)
    return {"note": "Rendered through Microsoft Word COM automation.", "artifacts": artifacts, "pages": pages}


